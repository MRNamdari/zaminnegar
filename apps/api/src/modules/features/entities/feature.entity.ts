import {
  Check,
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  OneToMany,
  OneToOne,
  PrimaryGeneratedColumn,
  Unique,
  UpdateDateColumn,
} from 'typeorm';
import { SRID_WGS84 } from '../../../common/geometry/geometry.constants';
import type { IMultiPolygon } from '../../../common/geometry/interfaces/multi-polygon.interface';
import { IFeature } from '../interfaces/feature.interface';

import {
  FEATURE_CONSTRAINTS,
  FEATURE_INDEXES,
  FEATURE_LIMITS,
  FEATURES_TABLE,
} from '../features.constants';
import { BlockEntity } from '../../blocks/entities/block.entity';
import { ProjectEntity } from '../../projects/entities/project.entity';
import { IProject } from '../../projects/interfaces/project.interface';
import { IParcel } from '../../parcels/interfaces/parcel.interface';
import { ParcelEntity } from '../../parcels/entities/parcel.entity';
import { IBlock } from '../../blocks/interfaces/block.interface';
import { RegionEntity } from '../../regions/entities/region.entity';
import { IRegion } from '../../regions/interfaces/region.interface';

/**
 * Persistence model of {@link IFeature}. The schema itself is created by migrations;
 * the decorators below document it and keep TypeORM's metadata accurate.
 */
@Entity({ name: FEATURES_TABLE })
@Unique(FEATURE_CONSTRAINTS.uniqueFeatureName, ['name'])
@Index(FEATURE_INDEXES.featureCreated, ['createdAt', 'id'])
@Check(FEATURE_CONSTRAINTS.checkGeometryValid, 'ST_IsValid("geom")')
export class FeatureEntity implements IFeature {
  @PrimaryGeneratedColumn('uuid', {
    name: 'id',
    primaryKeyConstraintName: FEATURE_CONSTRAINTS.primaryKey,
  })
  id!: string;

  @Column({ name: 'project_id', type: 'uuid' })
  projectId!: string;

  @Column({
    name: 'name',
    type: 'varchar',
    length: FEATURE_LIMITS.nameMaxLength,
  })
  name!: string;

  /** Stored as `geometry(MultiPolygon, 4326)`; TypeORM reads and writes it as GeoJSON. */
  @Index(FEATURE_INDEXES.geomGist, { spatial: true })
  @Column({
    name: 'geom',
    type: 'geometry',
    spatialFeatureType: 'MultiPolygon',
    srid: SRID_WGS84,
  })
  geometry!: IMultiPolygon;

  /** Generated by the database; never written by the application. */
  @Column({
    name: 'area_m2',
    type: 'double precision',
    generatedType: 'STORED',
    asExpression: 'ST_Area(geom::geography)',
    insert: false,
    update: false,
  })
  areaM2!: number;

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt!: Date;

  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' })
  updatedAt!: Date;

  @ManyToOne(() => ProjectEntity, (project) => project.features, {
    onDelete: 'CASCADE',
    nullable: false,
  })
  @JoinColumn({
    name: 'project_id',
    foreignKeyConstraintName: FEATURE_CONSTRAINTS.foreignKeyProject,
  })
  project?: IProject;

  @OneToOne(() => RegionEntity, (region) => region.feature, {
    onDelete: 'SET NULL',
    nullable: true,
  })
  region?: IRegion;

  @OneToOne(() => BlockEntity, (block) => block.feature, {
    onDelete: 'SET NULL',
    nullable: true,
  })
  block?: IBlock;

  @OneToOne(() => ParcelEntity, (parcel) => parcel.feature, {
    onDelete: 'SET NULL',
    nullable: true,
  })
  parcel?: IParcel;
}
