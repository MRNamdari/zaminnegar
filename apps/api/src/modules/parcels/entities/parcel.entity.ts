import {
  Check, Column, CreateDateColumn, Entity, Index, JoinColumn, ManyToOne, OneToMany, PrimaryGeneratedColumn, Unique, UpdateDateColumn,
} from 'typeorm';
import { SRID_WGS84 } from '../../../common/geometry/geometry.constants';
import type { IMultiPolygon } from '../../../common/geometry/interfaces/multi-polygon.interface';
import { BlockEntity } from '../../blocks/entities/block.entity';
import type { IBlock } from '../../blocks/interfaces/block.interface';
import { ParcelOwnerEntity } from '../../owners/entities/parcel-owner.entity';
import type { IParcelOwner } from '../../owners/interfaces/owner.interface';
import { ProjectEntity } from '../../projects/entities/project.entity';
import type { IProject } from '../../projects/interfaces/project.interface';
import type { IParcel } from '../interfaces/parcel.interface';
import { PARCEL_CONSTRAINTS, PARCEL_DEFAULTS, PARCEL_INDEXES, PARCEL_LIMITS, PARCELS_TABLE } from '../parcels.constants';

/**
 * Persistence model of {@link IParcel}. The schema itself is created by migrations;
 * the decorators below document it and keep TypeORM's metadata accurate.
 */
@Entity({ name: PARCELS_TABLE })
@Unique(PARCEL_CONSTRAINTS.uniqueProjectName, ['projectId', 'name'])
@Index(PARCEL_INDEXES.projectCreated, ['projectId', 'createdAt', 'id'])
@Check(PARCEL_CONSTRAINTS.checkGeometryValid, 'ST_IsValid("geom")')
@Check(PARCEL_CONSTRAINTS.checkFillColor, `"fill_color" ~ '^#[0-9A-Fa-f]{6}$'`)
@Check(PARCEL_CONSTRAINTS.checkStrokeColor, `"stroke_color" ~ '^#[0-9A-Fa-f]{6}$'`)
@Check(PARCEL_CONSTRAINTS.checkFillOpacity, '"fill_opacity" BETWEEN 0 AND 1')
@Check(PARCEL_CONSTRAINTS.checkStrokeWidth, `"stroke_width" BETWEEN ${PARCEL_LIMITS.strokeWidthMin} AND ${PARCEL_LIMITS.strokeWidthMax}`)
export class ParcelEntity implements IParcel {
  @PrimaryGeneratedColumn('uuid', { name: 'id', primaryKeyConstraintName: PARCEL_CONSTRAINTS.primaryKey })
  id!: string;

  @Column({ name: 'project_id', type: 'uuid' })
  projectId!: string;

  @Column({ name: 'block_id', type: 'uuid', nullable: true })
  blockId?: string | null;

  @Column({ name: 'name', type: 'varchar', length: PARCEL_LIMITS.nameMaxLength })
  name!: string;

  /** Stored as `geometry(MultiPolygon, 4326)`; TypeORM reads and writes it as GeoJSON. */
  @Index(PARCEL_INDEXES.geomGist, { spatial: true })
  @Column({ name: 'geom', type: 'geometry', spatialFeatureType: 'MultiPolygon', srid: SRID_WGS84 })
  geometry!: IMultiPolygon;

  @Column({ name: 'fill_color', type: 'varchar', length: 7, default: PARCEL_DEFAULTS.fillColor })
  fillColor!: string;

  @Column({ name: 'fill_opacity', type: 'double precision', default: PARCEL_DEFAULTS.fillOpacity })
  fillOpacity!: number;

  @Column({ name: 'stroke_color', type: 'varchar', length: 7, default: PARCEL_DEFAULTS.strokeColor })
  strokeColor!: string;

  @Column({ name: 'stroke_width', type: 'double precision', default: PARCEL_DEFAULTS.strokeWidth })
  strokeWidth!: number;

  @Column({ name: 'notes', type: 'text', nullable: true })
  notes!: string | null;

  /** Generated by the database; never written by the application. */
  @Column({
    name: 'area_m2',
    type: 'double precision',
    generatedType: 'STORED',
    asExpression: 'ST_Area(geom::geography)',
    insert: false,
    update: false,
  })
  areaM2!: number;

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt!: Date;

  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' })
  updatedAt!: Date;

  @ManyToOne(() => ProjectEntity, (project) => project.parcels, { onDelete: 'CASCADE', nullable: false })
  @JoinColumn({ name: 'project_id', foreignKeyConstraintName: PARCEL_CONSTRAINTS.foreignKeyProject })
  project?: IProject;

  @ManyToOne(() => BlockEntity, (block) => block.parcels, { onDelete: 'SET NULL', nullable: true })
  @JoinColumn({ name: 'block_id', foreignKeyConstraintName: 'fk_parcels_block_id' })
  block?: IBlock;

  @OneToMany(() => ParcelOwnerEntity, (parcelOwner) => parcelOwner.parcel)
  owners?: IParcelOwner[];
}
