import {
  Check,
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  OneToMany,
  OneToOne,
  PrimaryGeneratedColumn,
  Unique,
  UpdateDateColumn,
} from 'typeorm';
import { BlockEntity } from '../../blocks/entities/block.entity';
import type { IBlock } from '../../blocks/interfaces/block.interface';
import { ParcelOwnerEntity } from '../../owners/entities/parcel-owner.entity';
import type { IParcelOwner } from '../../owners/interfaces/owner.interface';
import { ProjectEntity } from '../../projects/entities/project.entity';
import type { IProject } from '../../projects/interfaces/project.interface';
import { IParcel, ParcelStatus } from '../interfaces/parcel.interface';
import {
  PARCEL_CONSTRAINTS,
  PARCEL_INDEXES,
  PARCEL_LIMITS,
  PARCELS_TABLE,
} from '../parcels.constants';
import { FeatureEntity } from '../../features/entities/feature.entity';
import { IFeature } from '../../features/interfaces/feature.interface';
import { RegionEntity } from '../../regions/entities/region.entity';
import { IRegion } from '../../regions/interfaces/region.interface';

/**
 * Persistence model of {@link IParcel}. The schema itself is created by migrations;
 * the decorators below document it and keep TypeORM's metadata accurate.
 */
@Entity({ name: PARCELS_TABLE })
@Unique(PARCEL_CONSTRAINTS.uniqueProjectName, ['projectId', 'name'])
@Index(PARCEL_INDEXES.projectCreated, ['projectId', 'createdAt', 'id'])
@Check(PARCEL_CONSTRAINTS.checkGeometryValid, 'ST_IsValid("geom")')
export class ParcelEntity implements IParcel {
  @PrimaryGeneratedColumn('uuid', {
    name: 'id',
    primaryKeyConstraintName: PARCEL_CONSTRAINTS.primaryKey,
  })
  id!: string;

  @Column({ name: 'feature_id', type: 'uuid' })
  featureId!: string;

  @Column({ name: 'project_id', type: 'uuid' })
  projectId!: string;

  @Column({ name: 'region_id', type: 'uuid' })
  regionId!: string;

  @Column({ name: 'block_id', type: 'uuid', nullable: true })
  blockId?: string | null;

  @Column({
    name: 'name',
    type: 'varchar',
    length: PARCEL_LIMITS.nameMaxLength,
  })
  name!: string;

  @Column({
    type: 'enum',
    enumName: PARCEL_CONSTRAINTS.parcelStatus,
    enum: ParcelStatus,
  })
  status!: ParcelStatus;

  /** Generated by the database; never written by the application. */
  @Column({
    name: 'area_m2',
    type: 'double precision',
    generatedType: 'STORED',
    asExpression: 'ST_Area(geom::geography)',
    insert: false,
    update: false,
  })
  areaM2!: number;

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt!: Date;

  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' })
  updatedAt!: Date;

  @OneToOne(() => FeatureEntity, (feature) => feature.parcel, {
    onDelete: 'CASCADE',
    nullable: false,
  })
  @JoinColumn({
    name: 'feature_id',
    foreignKeyConstraintName: PARCEL_CONSTRAINTS.foreignKeyFeature,
  })
  feature?: IFeature;

  @ManyToOne(() => ProjectEntity, (project) => project.parcels, {
    onDelete: 'CASCADE',
    nullable: false,
  })
  @JoinColumn({
    name: 'project_id',
    foreignKeyConstraintName: PARCEL_CONSTRAINTS.foreignKeyProject,
  })
  project?: IProject;

  @ManyToOne(() => RegionEntity, (region) => region.parcels, {
    onDelete: 'CASCADE',
    nullable: false,
  })
  @JoinColumn({
    name: 'region_id',
    foreignKeyConstraintName: PARCEL_CONSTRAINTS.foreignKeyRegion,
  })
  region?: IRegion;

  @ManyToOne(() => BlockEntity, (block) => block.parcels, {
    onDelete: 'SET NULL',
    nullable: true,
  })
  @JoinColumn({
    name: 'block_id',
    foreignKeyConstraintName: 'fk_parcels_block_id',
  })
  block?: IBlock;

  @OneToMany(() => ParcelOwnerEntity, (parcelOwner) => parcelOwner.parcel)
  owners?: IParcelOwner[];
}
